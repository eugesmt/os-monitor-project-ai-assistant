import tempfile
import unittest
from pathlib import Path

from dev_assistant.chunking import (
    build_corpus,
    chunk_go,
    chunk_markdown,
    corpus_fingerprint,
    go_sources,
    markdown_sources,
)


class ChunkingTests(unittest.TestCase):
    def test_corpus_is_limited_to_documentation(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            (root / "README.md").write_text("# Project\n\n## API\n\nGET /api/health\n", encoding="utf-8")
            (root / "docs").mkdir()
            (root / "docs" / "design.md").write_text("# Design\n\n## Flow\n\nRAG flow\n", encoding="utf-8")
            (root / "secret.txt").write_text("do not index", encoding="utf-8")
            sources = markdown_sources(root)
            self.assertEqual([path.relative_to(root).as_posix() for path in sources], ["README.md", "docs/design.md"])
            self.assertEqual({chunk.source for chunk in build_corpus(root)}, {"README.md", "docs/design.md"})

    def test_large_section_has_overlap_and_heading_metadata(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            path = root / "README.md"
            words = " ".join(f"word{i}" for i in range(30))
            path.write_text(f"# Project\n\n## API\n\n{words}\n", encoding="utf-8")
            chunks = chunk_markdown(path, root, max_words=10, overlap=2)
            self.assertGreater(len(chunks), 2)
            self.assertEqual(chunks[0].heading_path, ("Project", "API"))
            self.assertIn("word8", chunks[1].text)

    def test_headings_inside_fenced_code_are_not_structure(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            path = root / "README.md"
            path.write_text(
                "# Project\n\n## API\n\n```markdown\n# Fake heading\n## Also fake\n```\n\nThe real API section continues.\n",
                encoding="utf-8",
            )
            chunks = chunk_markdown(path, root)
            self.assertEqual(len(chunks), 1)
            self.assertEqual(chunks[0].heading_path, ("Project", "API"))
            self.assertIn("Fake heading", chunks[0].text)

    def test_chunk_embedding_text_keeps_parent_heading_context(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            path = root / "README.md"
            path.write_text("# Project\n\n## Архитектура\n\n### Системная схема\n\nCollector -> Runtime.\n", encoding="utf-8")
            chunks = chunk_markdown(path, root)
            self.assertEqual(chunks[0].heading_path, ("Project", "Архитектура", "Системная схема"))
            self.assertTrue(chunks[0].text.startswith("Project > Архитектура > Системная схема"))

    def test_go_sources_include_tests_and_exclude_generated_and_build_artifacts(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            (root / "internal").mkdir()
            (root / "internal" / "task.go").write_text("package internal\n", encoding="utf-8")
            (root / "internal" / "task_test.go").write_text("package internal\n", encoding="utf-8")
            (root / "internal" / "task_gen.go").write_text("package internal\n", encoding="utf-8")
            (root / "internal" / "generated.go").write_text("package internal\n", encoding="utf-8")
            (root / "vendor").mkdir()
            (root / "vendor" / "third_party.go").write_text("package vendor\n", encoding="utf-8")
            (root / "dist").mkdir()
            (root / "dist" / "artifact.go").write_text("package dist\n", encoding="utf-8")
            generated = root / "internal" / "wire.go"
            generated.write_text("// Code generated by wire; DO NOT EDIT.\npackage internal\n", encoding="utf-8")

            self.assertEqual(
                [path.relative_to(root).as_posix() for path in go_sources(root)],
                ["internal/task.go", "internal/task_test.go"],
            )

    def test_go_chunking_is_structural_and_keeps_declaration_metadata(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            path = root / "task.go"
            path.write_text(
                """package task

const Version = 1
var Default = Version
type Task struct { ID int }
func NewTask() Task { return Task{} }
func (t *Task) Save() error { return nil }
""",
                encoding="utf-8",
            )

            chunks = chunk_go(path, root)
            self.assertEqual(
                [chunk.section for chunk in chunks],
                ["const Version", "var Default", "type Task", "func NewTask", "method (t *Task).Save"],
            )
            self.assertTrue(all(chunk.source == "task.go" for chunk in chunks))
            self.assertTrue(all(chunk.chunking_strategy == "go-structural" for chunk in chunks))
            self.assertIn("func NewTask", next(chunk.text for chunk in chunks if chunk.section == "func NewTask"))
            self.assertLess(
                next(chunk.start_line for chunk in chunks if chunk.section == "type Task"),
                next(chunk.start_line for chunk in chunks if chunk.section == "func NewTask"),
            )

    def test_go_doc_comments_attach_to_following_declaration(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            path = root / "task.go"
            path.write_text(
                """package task

const Version = 1

// NewTask creates a task.
// It starts with an empty ID.
func NewTask() Task { return Task{} }
""",
                encoding="utf-8",
            )

            chunks = chunk_go(path, root)
            version = next(chunk for chunk in chunks if chunk.section == "const Version")
            constructor = next(chunk for chunk in chunks if chunk.section == "func NewTask")
            self.assertNotIn("NewTask creates", version.text)
            self.assertIn("NewTask creates", constructor.text)
            self.assertIn("It starts with an empty ID", constructor.text)
            self.assertEqual(constructor.start_line, 5)

    def test_go_declaration_embedding_includes_package_and_import_context(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            path = root / "task.go"
            path.write_text(
                """package task

import (
    "fmt"
    "strings"
)

func Format(value string) string { return fmt.Sprint(strings.TrimSpace(value)) }
""",
                encoding="utf-8",
            )

            chunk = chunk_go(path, root)[0]
            self.assertIn("package task", chunk.text)
            self.assertIn("imports: fmt, strings", chunk.text)
            self.assertIn("func Format", chunk.text)
            self.assertEqual(chunk.start_line, 8)

    def test_corpus_fingerprint_changes_when_go_source_changes(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            path = root / "main.go"
            path.write_text("package main\n\nfunc main() {}\n", encoding="utf-8")
            before = corpus_fingerprint(root)
            path.write_text("package main\n\nfunc main() { println(1) }\n", encoding="utf-8")
            self.assertNotEqual(before, corpus_fingerprint(root))


if __name__ == "__main__":
    unittest.main()
